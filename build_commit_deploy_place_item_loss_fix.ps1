Assert-Contains (Join-Path $ServerRepo "src/server_phase8_world_action_routes.ts") "deferred_inventory_commit" `
    "the atomic seed commit is missing from the world_seed_update route"
Assert-Contains (Join-Path $ServerRepo "src/server_phase11a_runtime.ts") "outbound_backpressure_forced" `
    "the new counters are missing from the stats snapshot allowlist and would be invisible"
if (-not $SkipClient) {
    Assert-Contains (Join-Path $ClientRepo "Scripts/block_manager.gd") "track_unpredicted_authoritative_place" `
        "tracking for placements the client does not predict is missing"
    Assert-Contains (Join-Path $ClientRepo "Scripts/block_manager.gd") "last_confirmed_place_visual_applied" `
        "the confirmed-place feedback flag is missing"
    Assert-Contains (Join-Path $ClientRepo "Scripts/world.gd") "handle_authoritative_seed_place_reconcile" `
        "the seed place reconciliation handler is missing"
    Assert-Contains (Join-Path $ClientRepo "Scripts/world.gd") "AUTHORITATIVE_SEED_PLACE_GIVE_UP_MS" `
        "the pending seed place give-up bound is missing"
    Assert-Contains (Join-Path $ClientRepo "Scripts/world_state_sync_manager.gd") "note_pending_authoritative_seed_place_removed" `
        "the seed removal note is missing from the sync manager"
}
Write-Host "  All source markers present." -ForegroundColor DarkGray

# -------------------------------------------------------------------------------------------
Write-Step "3/6  Building the four affected server modules"
# Leaves first, server entry last.
if ($DryRun) {
    foreach ($module in $Modules) {
        Write-Host "  [DryRun] would run: npm run $($module.Script)" -ForegroundColor DarkYellow
    }
} else {
    Push-Location $ServerRepo
    try {
        foreach ($module in $Modules) {
            Write-Host "  npm run $($module.Script)   ($($module.Name))" -ForegroundColor DarkGray
            npm run $($module.Script)
            if ($LASTEXITCODE -ne 0) { throw "FAILED: npm run $($module.Script)" }
        }
    } finally {
        Pop-Location
    }
    Write-Host "  All four builds passed." -ForegroundColor DarkGray
}

# -------------------------------------------------------------------------------------------
Write-Step "4/6  Verifying each generated .js actually contains the new code"
# THE GUARD. A green build does not prove the sync step wrote the new code into the files the
# server actually runs -- and with four modules there are four chances to ship a stale one.
if ($DryRun) {
    Write-Host "  [DryRun] skipping artifact verification (nothing was built)." -ForegroundColor DarkYellow
} else {
    foreach ($module in $Modules) {
        foreach ($marker in $module.Markers) {
            Assert-Contains (Join-Path $ServerRepo $($module.Artifact)) $marker `
                "STALE ARTIFACT: $($module.Artifact) was not regenerated. Run 'npm run $($module.Script)' and re-check."
        }
        Write-Host "  $($module.Artifact) is in sync with source." -ForegroundColor Green
    }
}


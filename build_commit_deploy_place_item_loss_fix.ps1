Write-Host "shipped by this script -- run the client from the Godot editor against staging to test" -ForegroundColor Yellow
Write-Host "them, and build/export the client when you want players to have them." -ForegroundColor Yellow
Write-Host ""
Write-Host "Verify on staging, in this order:" -ForegroundColor Yellow
Write-Host "  1. Place blocks and plant seeds normally -> no visible change, no double particles,"
Write-Host "     inventory counts still match after each action."
Write-Host "  2. Place a World Lock / Small Lock and a water bucket (the un-predicted paths)"
Write-Host "     -> they still appear and are still charged exactly once."
Write-Host "  3. Throttle the client's connection (Clumsy, or a phone on a weak signal), then"
Write-Host "     place a block and plant a seed -> both eventually appear, and no item is lost."
Write-Host "  4. Harvest a seed and immediately replant on the same tile -> the new plant survives."
Write-Host ""
Write-Host "Watch for these in the staging logs:" -ForegroundColor Yellow
Write-Host "    sudo -u pixelmania-stg pm2 logs --lines 200 --nostream"

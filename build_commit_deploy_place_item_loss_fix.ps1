Write-Step "5/6  Committing (named files only)"

function Commit-Repo($repo, $files, $message, $label) {
    $existing = @()
    foreach ($f in $files) {
        if (Test-Path -LiteralPath (Join-Path $repo $f)) { $existing += $f }
        else { Write-Host "  skipping missing $label file: $f" -ForegroundColor DarkYellow }
    }
    if ($existing.Count -eq 0) {
        Write-Host "  Nothing to add for $label." -ForegroundColor DarkYellow
        return
    }

    if ($DryRun) {
        Write-Host "  [DryRun] would: git -C $repo add $($existing -join ' ')" -ForegroundColor DarkYellow
        Write-Host "  [DryRun] would: git -C $repo commit -m ""$message""" -ForegroundColor DarkYellow
        return
    }

    git -C $repo add -- $existing
    if ($LASTEXITCODE -ne 0) { throw "FAILED: git add in $repo" }

    # Nothing staged is a normal outcome when re-running after a partial failure, not an error.
    git -C $repo diff --cached --quiet -- $existing
    if ($LASTEXITCODE -eq 0) {
        # ${label} not $label -- PowerShell reads "$label:" as a scope-qualified variable.
        Write-Host "  ${label}: no changes staged, skipping commit." -ForegroundColor DarkGray
        return
    }

    git -C $repo commit -m $message
    if ($LASTEXITCODE -ne 0) { throw "FAILED: git commit in $repo" }
    Write-Host "  $label committed." -ForegroundColor Green
}

Commit-Repo $ServerRepo ($ServerSources + $ServerArtifacts) $ServerMessage "server"
if (-not $SkipClient) {
    Commit-Repo $ClientRepo $ClientFiles $ClientMessage "client"
} else {
    Write-Host "  -SkipClient set, leaving the client repo alone." -ForegroundColor DarkYellow
}

if ($Push -and -not $DryRun) {
    $reposToPush = @($ServerRepo)
    if (-not $SkipClient) { $reposToPush += $ClientRepo }
    foreach ($repo in $reposToPush) {
        $branch = (git -C $repo rev-parse --abbrev-ref HEAD).Trim()
        Write-Host "  pushing $repo ($branch) to origin" -ForegroundColor DarkGray
        git -C $repo push origin $branch
        if ($LASTEXITCODE -ne 0) { throw "FAILED: git push in $repo" }
    }
} elseif ($Push) {
    Write-Host "  [DryRun] would push each repo's current branch to origin." -ForegroundColor DarkYellow
}

# Surface anything else that is dirty, so an unrelated file is noticed rather than silently left
# behind (the deploy preflight refuses if anything else in the server repo is dirty).
if (-not $DryRun) {
    $dirty = git -C $ServerRepo status --porcelain
    if ($dirty) {
        Write-Host ""
        Write-Host "  NOTE: other uncommitted changes remain in the server repo:" -ForegroundColor DarkYellow
        $dirty | ForEach-Object { Write-Host "    $_" -ForegroundColor DarkYellow }
        Write-Host "  If any are GENERATED .js files, the deploy preflight will refuse until they are" -ForegroundColor DarkYellow
        Write-Host "  committed. Anything else (e.g. other in-progress work) is fine to leave." -ForegroundColor DarkYellow
    }
}

# -------------------------------------------------------------------------------------------
Write-Step "6/6  Deploying to STAGING"

# deploy_to_droplet.ps1's Assert-LocalPreflightPreservedBackendCommit demands the backend repo be
# COMPLETELY clean -- no tracked diff vs HEAD, and no untracked files at all. Checking it HERE
# turns that into a clear, actionable message instead of an exception thrown from deep inside
# deploy_to_droplet.ps1.
if (-not $DryRun) {
    $trackedDirty = git -C $ServerRepo diff --name-only HEAD --
    $untracked = git -C $ServerRepo ls-files --others --exclude-standard
    if ($trackedDirty -or $untracked) {
        Write-Host ""
        Write-Host "  Backend repo is not clean, so the deploy would refuse:" -ForegroundColor Red
        if ($trackedDirty) {
            Write-Host "    modified (tracked):" -ForegroundColor Red
            $trackedDirty | ForEach-Object { Write-Host "      $_" -ForegroundColor Red }
        }
        if ($untracked) {
            Write-Host "    untracked:" -ForegroundColor Red
            $untracked | ForEach-Object { Write-Host "      $_" -ForegroundColor Red }
        }
        Write-Host ""
        Write-Host "  Commit them, or add them to .gitignore if they are scratch files:" -ForegroundColor Yellow
        Write-Host "      git -C `"$ServerRepo`" add -A"
        Write-Host "      git -C `"$ServerRepo`" commit -m ""chore: commit remaining backend files before deploy"""
        Write-Host ""
        Write-Host "  Careful with 'add -A' if you have work-in-progress you do NOT want committed" -ForegroundColor Yellow
        Write-Host "  -- add those to .gitignore or stash them instead." -ForegroundColor Yellow
        throw "Backend repo not clean; refusing to start the deploy."
    }
    Write-Host "  Backend repo is clean." -ForegroundColor DarkGray
}

if ($SkipDeploy) {
    Write-Host "  -SkipDeploy set. Deploy manually with:  .\deploy_staging.ps1" -ForegroundColor Yellow
} elseif ($DryRun) {
    Write-Host "  [DryRun] would run: .\deploy_staging.ps1" -ForegroundColor DarkYellow
} else {
    Push-Location $ServerRepo
    try {
        # Staging only. This script never calls promote_staging_to_production.ps1.
        if ($Fast) { .\deploy_staging.ps1 -Fast } else { .\deploy_staging.ps1 }
        if ($LASTEXITCODE -ne 0) { throw "FAILED: deploy_staging.ps1" }
    } finally {
        Pop-Location
    }
    Write-Host "  Deployed to staging." -ForegroundColor Green
}


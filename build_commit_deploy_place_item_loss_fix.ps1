<#
    PixelMania - one-command build + commit + deploy for the "item consumed but the block or
    seed never placed" fix (reported as happening during signal jitter).

    WHAT THE FIX IS
    ---------------
    server_socket_delivery_helpers.ts::sendRawJsonToSocket() silently discarded ANY packet once
    socket.bufferedAmount passed SERVER_WEBSOCKET_MAX_BUFFERED_AMOUNT -- no queue, no retry.
    Only player_position_batch had its own coalescing retry queue; the authoritative world_update
    place echo and the inventory delta shared the same drop path. The placement itself was already
    atomic, so the server had the block and had charged the item while the client was simply never
    told. Now only packet types in droppablePacketTypes may be dropped; everything else is handed
    to ws to queue in order, and past a much higher hard ceiling the socket is terminated so the
    client reconnects and resyncs from PostgreSQL.

    Also in this change: the legacy world_seed_update route now commits the seed cost atomically
    with world state, and the client tracks/reconciles placements it did not predict (locks, water,
    opt-out items) and seed plants, so a lost echo self-heals instead of persisting.

    WHY THIS SCRIPT EXISTS
    ----------------------
    src/*.ts is source; the server actually runs the generated root-level *.js. This change touches
    FOUR server modules, so four separate builds have to run -- src/server.ts alone is not enough.
    A commit made without rebuilding all four would look complete and deploy cleanly while changing
    nothing at runtime. STEP 4 re-reads each generated .js and asserts the new code is really in it,
    so a silently stale artifact fails HERE instead of shipping nothing. Same failure class the
    header of build_commit_deploy_takeworld_giveworld.ps1 documents.

    WHAT IT DOES
    ------------
      1. Sanity-checks both repo paths.
      2. Confirms every source edit is present (did the write-backs actually land?).
      3. Builds the four affected server modules, leaves first, server entry last.
      4. Verifies each generated .js really contains the new code (the stale-artifact guard).
      5. Commits ONLY the named files in each repo (never a blanket `git add -A`).
      6. Runs .\deploy_staging.ps1   (STAGING only -- see SAFETY)

    SAFETY
    ------
      * Never runs promote_staging_to_production.ps1. Staging only, by construction.
      * Only ever `git add`s an explicit list of files, so unrelated work-in-progress in either
        repo is never swept in.
      * Skips the commit step cleanly when a repo has nothing staged, so re-running after a
        partial failure (e.g. the deploy failed) is safe.
      * The Godot client changes are committed to the pixel-mania repo but are NOT shipped by
        deploy_staging.ps1 -- that only packages the backend. Run the client from the Godot editor
        to test them; players get them on the next client build/export.
      * -Push is off by default. Nothing is pushed to GitHub unless you ask for it.

    USAGE
        cd D:\Pixelmania\PixelMania\PixelManiaServer
        .\build_commit_deploy_place_item_loss_fix.ps1                 # build, commit both repos, deploy to staging
        .\build_commit_deploy_place_item_loss_fix.ps1 -DryRun         # show what would happen, change nothing
        .\build_commit_deploy_place_item_loss_fix.ps1 -SkipDeploy     # build + commit only
        .\build_commit_deploy_place_item_loss_fix.ps1 -Fast           # deploy with -Fast (skips local check:security preflight)
        .\build_commit_deploy_place_item_loss_fix.ps1 -Push           # also push each repo's current branch to origin
        .\build_commit_deploy_place_item_loss_fix.ps1 -SkipClient     # leave the pixel-mania repo alone
#>

param(

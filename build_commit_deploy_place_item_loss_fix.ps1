Write-Host "  Client: $ClientRepo" -ForegroundColor DarkGray

# -------------------------------------------------------------------------------------------
Write-Step "2/6  Confirming the source edits are present"
# Cheap, high-signal markers. If a write-back never landed or a file got reverted, this fails

        Artifact = "server_phase11a_runtime.js"
        Markers  = @("outbound_backpressure_forced", "outbound_backpressure_disconnects")
    },
    @{
        Name     = "server entry"
        Script   = "build:server-entry"
        Artifact = "server.js"
        Markers  = @("SERVER_WEBSOCKET_CRITICAL_BUFFERED_AMOUNT", "authoritative_seed_present", "outbound_backpressure_disconnects")
    }
)

function Write-Step($text) {
    Write-Host ""
    Write-Host "=== $text ===" -ForegroundColor Cyan
}

function Assert-Contains($path, $needle, $why) {
    if (-not (Test-Path -LiteralPath $path)) { throw "Missing expected file: $path" }
    $content = Get-Content -LiteralPath $path -Raw
    if (-not $content.Contains($needle)) {
        throw "$path is missing '$needle' -- $why"
    }
}


        Script   = "build:server-socket-delivery-helpers"
        Artifact = "server_socket_delivery_helpers.js"
        Markers  = @("socket_backpressure_queued", "socket_backpressure_disconnect", "outbound_backpressure_forced")
    },
    @{
        Name     = "phase8 world action routes"

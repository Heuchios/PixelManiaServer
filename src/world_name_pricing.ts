function buildPremiumMultipliers(): Readonly<Record<string, number>> {
  const prices: Record<string, number> = Object.create(null);
  for (const group of PREMIUM_NAME_GROUPS) {
    for (const name of group.names) {
      // A name may fit multiple categories; its highest listed price wins.
      if (!/^[A-Z0-9]{1,32}$/.test(name)) throw new Error(`Invalid premium world name: ${name}`);
      prices[name] = Math.max(prices[name] || 0, group.price_gems / BASE_PRICE_GEMS);
    }
  }
  return Object.freeze(prices);
}

export const PREMIUM_MULTIPLIERS = buildPremiumMultipliers();

export interface NameQuote {
  name: string;
  price_gems: number;
  base_price_gems: number;
  multiplier: number;
  tier: "premium" | "short" | "letters" | "standard";
  pricing_version: number;
  reservation_duration_ms: number;
}

export function quoteWorldName(value: unknown): NameQuote {
  // Reject rather than strip characters: invalid inputs must never alias names.
  if (typeof value !== "string" || value.length < 1 || value.length > 32 || /[^A-Za-z0-9]/.test(value)) {
    throw new Error("World names must be 1-32 ASCII letters or numbers.");
  }
  const name = value.toUpperCase();
  const shortMultipliers = [1000, 500, 100];
  const letterMultipliers: Record<number, number> = { 4: 50, 5: 20, 6: 10, 7: 5 };
  const premium = Object.hasOwn(PREMIUM_MULTIPLIERS, name) ? PREMIUM_MULTIPLIERS[name] : 0;
  const short = shortMultipliers[name.length - 1] || 0;
  const letters = /^[A-Z]+$/.test(name) ? (letterMultipliers[name.length] || 2) : 0;
  const multiplier = Math.max(1, premium, short, letters);
  return {
    name,
    price_gems: BASE_PRICE_GEMS * multiplier,
    base_price_gems: BASE_PRICE_GEMS,
    multiplier,
    tier: premium ? "premium" : short ? "short" : letters ? "letters" : "standard",
    pricing_version: PRICING_VERSION,
    reservation_duration_ms: RESERVATION_DURATION_MS,
  };
}

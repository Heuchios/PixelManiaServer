set_env OPS_DASHBOARD_LOGIN_CODE_TTL_MINUTES 10
set_env OPS_DASHBOARD_ACCOUNT_BACKUP_DIR /var/backups/pixelmania/ops-dashboard
set_env OPS_DASHBOARD_ACCOUNT_BACKUP_RETENTION_DAYS 30
set_env OPS_DASHBOARD_ACCOUNT_BACKUP_SCHEDULE "17 * * * *"
set_env OPS_DASHBOARD_DOMAIN ops.pixelmaniagame.com
set_env OPS_DASHBOARD_HEALTH_URL __HEALTH_URL__
set_env OPS_DASHBOARD_ROUTE_TARGETS "ws-a|pixelmania-a|http://127.0.0.1:18091/health|wss://api.pixelmaniagame.com/ws-a;ws-b|pixelmania-b|http://127.0.0.1:18092/health|wss://api.pixelmaniagame.com/ws-b"
set_env OPS_DASHBOARD_PM2_APP pixelmania

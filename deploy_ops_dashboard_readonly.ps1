set_env OPS_DASHBOARD_STOP_COMMAND 'for app in pixelmania pixelmania-a pixelmania-b; do pm2 stop "$app" || true; done; pm2 save'
set_env OPS_DASHBOARD_ALLOW_STOP_WITH_PLAYERS false
set_env OPS_DASHBOARD_ALLOW_DEPLOY_WITH_PLAYERS false
set_env OPS_DASHBOARD_ALLOW_ROLLBACK_WITH_PLAYERS false
set_env OPS_DASHBOARD_CONFIRM_ACTIONS stop,deploy,rollback
set_env OPS_DASHBOARD_ROLLBACK_COMMAND "bash scripts/ops_dashboard_git_rollback.sh"

node --check ops_dashboard_server.js
node --check ecosystem.ops.config.js
node --check scripts/generate_ops_dashboard_token_hash.js
node --check scripts/generate_ops_dashboard_password_hash.js
chmod +x scripts/start_route_production_instances.sh scripts/ops_dashboard_git_deploy.sh scripts/ops_dashboard_git_rollback.sh scripts/ops_dashboard_account_backup.sh scripts/install_ops_dashboard_backup_cron.sh scripts/install_ops_dashboard_https.sh
bash -n scripts/start_route_production_instances.sh
bash -n scripts/ops_dashboard_git_deploy.sh
bash -n scripts/ops_dashboard_git_rollback.sh
bash -n scripts/ops_dashboard_account_backup.sh
bash -n scripts/install_ops_dashboard_backup_cron.sh
bash -n scripts/install_ops_dashboard_https.sh
pm2 startOrReload ecosystem.ops.config.js --env production --update-env
pm2 save

echo "== pixelmania-ops status =="
pm2 describe pixelmania-ops

echo "== local dashboard auth check =="
status_code="$(curl -sS -o /tmp/pixelmania-ops-auth.json -w '%{http_code}' http://127.0.0.1:__OPS_PORT__/api/status || true)"
cat /tmp/pixelmania-ops-auth.json || true
echo
if [ "$status_code" != "401" ]; then
  echo "Expected unauthenticated /api/status to return 401, got ${status_code}."
  exit 1
fi

echo "PixelMania ops dashboard is running read-only on 127.0.0.1:__OPS_PORT__."
'@

$remoteCommand = $remoteCommand.
  Replace("__REMOTE_PATH__", $remotePath).
  Replace("__OPS_HASH__", $hashLiteral).
  Replace("__OPS_ADMIN_USERNAME__", $adminUsernameLiteral).
  Replace("__OPS_ADMIN_EMAIL__", $adminEmailLiteral).
  Replace("__OPS_ADMIN_PASSWORD_HASH__", $adminPasswordHashLiteral).
  Replace("__OPS_PUBLIC_BASE_URL__", $publicBaseUrlLiteral).
  Replace("__OPS_PORT__", $portRaw).
  Replace("__HEALTH_URL__", $healthLiteral)

$remoteBootstrap = "$remotePath/scripts/deploy_ops_dashboard_readonly_remote.sh"
$tempBootstrap = Join-Path ([System.IO.Path]::GetTempPath()) ("pixelmania-ops-dashboard-" + [guid]::NewGuid().ToString("N") + ".sh")
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($tempBootstrap, $remoteCommand, $utf8NoBom)
try {
  & scp @sshBaseArgs $tempBootstrap "${sshTarget}:$remoteBootstrap"
  if ($LASTEXITCODE -ne 0) { throw "scp failed for remote ops dashboard bootstrap." }
  Invoke-RemoteCommand "chmod +x $remoteBootstrap && bash $remoteBootstrap"
} finally {
  Remove-Item -LiteralPath $tempBootstrap -ErrorAction SilentlyContinue
}

Write-Host ""
Write-Host "Read-only PixelMania ops dashboard is deployed."
Write-Host "Open it with an SSH tunnel:"
Write-Host "ssh -L ${OpsDashboardPort}:127.0.0.1:${OpsDashboardPort} ${sshTarget}"
Write-Host "Then browse to http://127.0.0.1:${OpsDashboardPort}"

param(
  [Parameter(Mandatory = $true, Position = 0)]
  [string]$RemoteIp,

  [string]$RemoteUser = "pixelmania",
  [string]$RemoteDir = "PixelManiaServer",
  [string]$SshKeyPath,
  [string]$OpsDashboardToken,
  [string]$OpsDashboardTokenHash,
  [string]$OpsDashboardAdminUsername = "admin",
  [string]$OpsDashboardAdminEmail = "",
  [string]$OpsDashboardAdminPassword,
  [string]$OpsDashboardAdminPasswordHash,
  [int]$OpsDashboardPort = 9090,
  [string]$HealthUrl = "http://127.0.0.1:8080/health"
)

$ErrorActionPreference = "Stop"

function ConvertTo-ShellLiteral {
  param([string]$Value)
  return "'" + $Value.Replace("'", "'\''") + "'"
}

function Get-Sha256Hex {
  param([string]$Value)
  $bytes = [System.Text.Encoding]::UTF8.GetBytes($Value)
  $hash = [System.Security.Cryptography.SHA256]::Create().ComputeHash($bytes)
  return (($hash | ForEach-Object { $_.ToString("x2") }) -join "")
}

function New-Base64UrlToken {
  $bytes = New-Object byte[] 32
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try {
    $rng.GetBytes($bytes)
  } finally {
    $rng.Dispose()
  }
  return [Convert]::ToBase64String($bytes).TrimEnd("=").Replace("+", "-").Replace("/", "_")
}

function Get-OpsDashboardPasswordHash {
  param([string]$Password)
  $helper = Join-Path $PSScriptRoot "scripts/generate_ops_dashboard_password_hash.js"
  if (-not (Test-Path -LiteralPath $helper)) {
    throw "Missing password hash helper: $helper"
  }
  $output = & node $helper $Password
  if ($LASTEXITCODE -ne 0) {
    throw "Password hash helper failed."
  }
  $line = $output | Where-Object { $_ -like "OPS_DASHBOARD_ADMIN_PASSWORD_HASH=*" } | Select-Object -First 1
  if (-not $line) {
    throw "Password hash helper did not print OPS_DASHBOARD_ADMIN_PASSWORD_HASH."
  }
  return $line.Substring("OPS_DASHBOARD_ADMIN_PASSWORD_HASH=".Length)
}

if (-not $OpsDashboardAdminPassword -and -not $OpsDashboardAdminPasswordHash) {
  $OpsDashboardAdminPassword = New-Base64UrlToken
  Write-Host ""
  Write-Host "Generated PixelMania Ops admin password. Save it now; only the hash will be installed on the server:"
  Write-Host "username: $OpsDashboardAdminUsername"
  Write-Host "password: $OpsDashboardAdminPassword"
  Write-Host ""
}

if ($OpsDashboardAdminPassword) {
  $OpsDashboardAdminPasswordHash = Get-OpsDashboardPasswordHash $OpsDashboardAdminPassword
}

if (-not ($OpsDashboardAdminPasswordHash -match "^scrypt:[0-9]+:[0-9]+:[0-9]+:[A-Za-z0-9_-]+:[a-fA-F0-9]+$")) {
  throw "OpsDashboardAdminPasswordHash must be generated by scripts/generate_ops_dashboard_password_hash.js."
}

if ($OpsDashboardToken) {
  $computedHash = Get-Sha256Hex $OpsDashboardToken
  if ($OpsDashboardTokenHash -and $OpsDashboardTokenHash.ToLowerInvariant() -ne $computedHash) {
    throw "OpsDashboardTokenHash does not match OpsDashboardToken."
  }
  $OpsDashboardTokenHash = $computedHash
}

if ($OpsDashboardTokenHash -and -not ($OpsDashboardTokenHash -match "^[a-fA-F0-9]{64}$")) {
  throw "OpsDashboardTokenHash must be a 64-character sha256 hex string."
}

if ($OpsDashboardPort -lt 1 -or $OpsDashboardPort -gt 65535) {
  throw "OpsDashboardPort must be between 1 and 65535."
}

if (-not $SshKeyPath -and $env:PIXELMANIA_SSH_KEY) {
  $SshKeyPath = $env:PIXELMANIA_SSH_KEY
}

if (-not $SshKeyPath) {
  $defaultSshKeyPath = Join-Path $HOME ".ssh/pixelmania_ed25519"
  if (Test-Path -LiteralPath $defaultSshKeyPath) {
    $SshKeyPath = $defaultSshKeyPath
  }
}

if ($SshKeyPath) {
  if (-not (Test-Path -LiteralPath $SshKeyPath)) {
    throw "SSH key not found: $SshKeyPath"
  }
  Write-Host "Using SSH key: $SshKeyPath"
  $sshBaseArgs = @("-i", $SshKeyPath, "-o", "BatchMode=yes")
} else {
  $sshBaseArgs = @()
}

$localOpsDashboardServer = Join-Path $PSScriptRoot "ops_dashboard_server.js"
$localOpsDashboardEcosystem = Join-Path $PSScriptRoot "ecosystem.ops.config.js"
$localOpsDashboardPublic = Join-Path $PSScriptRoot "ops_dashboard_public"
$localOpsDashboardEnvExample = Join-Path $PSScriptRoot ".env.ops.example"
$localOpsDashboardDoc = Join-Path $PSScriptRoot "docs/ops_dashboard.md"
$localOpsDashboardTokenHelper = Join-Path $PSScriptRoot "scripts/generate_ops_dashboard_token_hash.js"
$localOpsDashboardPasswordHelper = Join-Path $PSScriptRoot "scripts/generate_ops_dashboard_password_hash.js"
$localRouteProductionSetup = Join-Path $PSScriptRoot "scripts/start_route_production_instances.sh"
$localOpsDashboardGitDeploy = Join-Path $PSScriptRoot "scripts/ops_dashboard_git_deploy.sh"
$localOpsDashboardGitRollback = Join-Path $PSScriptRoot "scripts/ops_dashboard_git_rollback.sh"
$localOpsDashboardAccountBackup = Join-Path $PSScriptRoot "scripts/ops_dashboard_account_backup.sh"
$localOpsDashboardBackupCron = Join-Path $PSScriptRoot "scripts/install_ops_dashboard_backup_cron.sh"
$localOpsDashboardHttps = Join-Path $PSScriptRoot "scripts/install_ops_dashboard_https.sh"

foreach ($path in @($localOpsDashboardServer, $localOpsDashboardEcosystem, $localOpsDashboardEnvExample, $localOpsDashboardDoc, $localOpsDashboardTokenHelper, $localOpsDashboardPasswordHelper, $localRouteProductionSetup, $localOpsDashboardGitDeploy, $localOpsDashboardGitRollback, $localOpsDashboardAccountBackup, $localOpsDashboardBackupCron, $localOpsDashboardHttps)) {
  if (-not (Test-Path -LiteralPath $path)) {
    throw "Missing file: $path"
  }
}
if (-not (Test-Path -LiteralPath $localOpsDashboardPublic)) {
  throw "Missing directory: $localOpsDashboardPublic"
}

$sshTarget = "${RemoteUser}@${RemoteIp}"
$remotePath = "~/$RemoteDir"

function Invoke-RemoteCommand {
  param([string]$Command)
  & ssh @sshBaseArgs "$sshTarget" $Command
  if ($LASTEXITCODE -ne 0) {
    throw "Remote command failed with exit code $LASTEXITCODE"
  }
}

Write-Host "Copying PixelMania ops dashboard files to ${sshTarget}:${remotePath}..."
Invoke-RemoteCommand "mkdir -p $remotePath/scripts $remotePath/docs $remotePath/ops_dashboard_public"
& scp @sshBaseArgs $localOpsDashboardServer "${sshTarget}:$remotePath/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard server." }
& scp @sshBaseArgs $localOpsDashboardEcosystem "${sshTarget}:$remotePath/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard PM2 config." }
& scp @sshBaseArgs $localOpsDashboardEnvExample "${sshTarget}:$remotePath/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard env example." }
& scp @sshBaseArgs -r $localOpsDashboardPublic "${sshTarget}:$remotePath/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard public files." }
& scp @sshBaseArgs $localOpsDashboardDoc "${sshTarget}:$remotePath/docs/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard docs." }
& scp @sshBaseArgs $localOpsDashboardTokenHelper "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard token helper." }
& scp @sshBaseArgs $localOpsDashboardPasswordHelper "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard password helper." }
& scp @sshBaseArgs $localRouteProductionSetup "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for route production helper." }
& scp @sshBaseArgs $localOpsDashboardGitDeploy "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard git deploy helper." }
& scp @sshBaseArgs $localOpsDashboardGitRollback "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard git rollback helper." }
& scp @sshBaseArgs $localOpsDashboardAccountBackup "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard account backup helper." }
& scp @sshBaseArgs $localOpsDashboardBackupCron "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard account backup cron helper." }
& scp @sshBaseArgs $localOpsDashboardHttps "${sshTarget}:$remotePath/scripts/"
if ($LASTEXITCODE -ne 0) { throw "scp failed for ops dashboard HTTPS helper." }

$hashLiteral = ConvertTo-ShellLiteral $(if ($OpsDashboardTokenHash) { $OpsDashboardTokenHash.ToLowerInvariant() } else { "" })
$adminUsernameLiteral = ConvertTo-ShellLiteral $OpsDashboardAdminUsername
$adminEmailLiteral = ConvertTo-ShellLiteral $OpsDashboardAdminEmail
$adminPasswordHashLiteral = ConvertTo-ShellLiteral $OpsDashboardAdminPasswordHash
$publicBaseUrlLiteral = ConvertTo-ShellLiteral "http://127.0.0.1:$OpsDashboardPort"
$portRaw = [string]$OpsDashboardPort
$healthLiteral = ConvertTo-ShellLiteral $HealthUrl

$remoteCommand = @'
set -euo pipefail
cd __REMOTE_PATH__

set_env() {
  key="$1"
  value="$2"
  touch .env

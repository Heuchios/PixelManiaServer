    sed -i "s/^${key}=.*/${key}=${escaped_value}/" .env
  else
    printf '\n%s=%s\n' "$key" "$value" >> .env
  fi
}

set_env OPS_DASHBOARD_HOST 127.0.0.1
set_env OPS_DASHBOARD_PORT __OPS_PORT__
set_env OPS_DASHBOARD_TOKEN ""
